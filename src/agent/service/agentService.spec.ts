import { ConfigService } from '@nestjs/config';
import type { IDbService } from '../../database/services/dbServiceInterface';
import type { IEmbeddingModel } from '../../embedding/services/geminiEmbeddingModelInterfaceService';
import { MastraFactory } from '../mastra/mastraFactory';
import { AgentService } from './agentService';
import { RagAgentError } from './agentServiceInterface';

// Mastra ships ESM-only dependencies that Jest cannot load, and the LLM must be faked anyway.
jest.mock('../mastra/mastraFactory', () => ({ MastraFactory: jest.fn() }));

describe('AgentService', () => {
  const db = {} as IDbService;
  const embeddingModel = {} as IEmbeddingModel;
  const config = {
    getOrThrow: () => 'fake-api-key',
  } as unknown as ConfigService;
  const generate = jest.fn();

  // Mirrors Mastra: asking for an agent that was not registered throws.
  const registeredAgents: Record<string, { generate: typeof generate }> = {
    assistantAgent: { generate },
  };

  beforeEach(() => {
    generate.mockReset();
    (MastraFactory as jest.Mock).mockReturnValue({
      getAgent: (name: string) => {
        const agent = registeredAgents[name];
        if (!agent) {
          throw new Error(`Agent with name ${name} not found`);
        }
        return agent;
      },
    });
  });

  it('returns the text generated by the registered agent', async () => {
    generate.mockResolvedValue({ text: 'The answer' });
    const service = new AgentService(db, embeddingModel, config);

    const result = await service.askRAGagent('A question');

    expect(result).toEqual({ IsSuccess: true, value: 'The answer' });
    expect(generate).toHaveBeenCalledWith('A question');
  });

  it('returns EmptyResponse when the agent produces no text', async () => {
    generate.mockResolvedValue({ text: '' });
    const service = new AgentService(db, embeddingModel, config);

    const result = await service.askRAGagent('A question');

    expect(result).toEqual({
      IsSuccess: false,
      error: RagAgentError.EmptyResponse,
    });
  });
});
